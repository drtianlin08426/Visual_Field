def generate_a4_report(report, analysis_result, out_dir: str, lang: str = "zh") -> str:
    """
    将 A4 报告写入 out_dir，文件名含患者姓名与日期，返回完整路径。
    lang: "zh"(默认) 或 "en"
    """
    os.makedirs(out_dir, exist_ok=True)
    safe_name = (report.patient_name or "患者").replace("/", "_").replace("\\", "_")
    safe_name = "".join(ch for ch in safe_name if ch.isalnum() or ch in " _-")
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    prefix = REPORT_UI[lang]["file_prefix"]
    fname = f"{prefix}_{safe_name}_{stamp}.html"
    out_path = os.path.join(out_dir, fname)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(build_a4_html(report, analysis_result, lang=lang))
    return out_path


