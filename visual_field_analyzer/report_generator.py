def render_grid_svg(eye: str, point_states: list, size: int = 360) -> str:
    """
    生成视野测试点分析示意图（SVG，内联）。
    绿色空心圆=已见，红色实心方块=未见，蓝圈=颞侧外点，紫圈=鼻侧边缘。
    """
    pts = get_points_for_eye(eye)
    t_idx = get_temporal_outer_point(eye)
    n_idx = set(get_nasal_edge_indices(eye))
    max_deg = 95.0
    c = size / 2.0
    scale = (size / 2.0 - 24) / max_deg  # 像素/度

    parts = []
    parts.append(f'<svg xmlns="http://www.w3.org/2000/svg" '
                 f'viewBox="0 0 {size} {size}" width="100%" '
                 f'style="max-width:{size}px;display:block;margin:auto;">')

    # 背景
    parts.append(f'<rect x="0" y="0" width="{size}" height="{size}" '
                 f'fill="#ffffff"/>')

    # 同心圆（10°~90°）
    for r_deg in range(10, int(max_deg) + 1, 10):
        r = r_deg * scale
        col = "#cfcfcf" if r_deg % 20 == 0 else "#e6e6e6"
        parts.append(f'<circle cx="{c:.1f}" cy="{c:.1f}" r="{r:.1f}" '
                     f'fill="none" stroke="{col}" stroke-width="1"/>')

    # 坐标轴
    ax = (size / 2.0 - 6)
    parts.append(f'<line x1="{c-ax:.1f}" y1="{c:.1f}" x2="{c+ax:.1f}" '
                 f'y2="{c:.1f}" stroke="#bbbbbb" stroke-width="1"/>')
    parts.append(f'<line x1="{c:.1f}" y1="{c-ax:.1f}" x2="{c:.1f}" '
                 f'y2="{c+ax:.1f}" stroke="#bbbbbb" stroke-width="1"/>')

    # 度数标注
    def _lbl(x, y, t):
        parts.append(f'<text x="{x:.1f}" y="{y:.1f}" font-size="11" '
                     f'fill="#888" font-family="Arial">{t}</text>')
    _lbl(c + ax - 2, c - 6, "90°")
    _lbl(c - ax + 2, c - 6, "-90°")
    _lbl(c + 4, c - ax + 12, "90°")
    _lbl(c + 4, c + ax - 4, "-90°")

    # 测试点
    for i, (gx, gy) in enumerate(pts):
        sx = c + gx * scale
        sy = c - gy * scale
        st = point_states[i] if i < len(point_states) else -1
        if st == 1:
            # 已见：绿色空心圆
            parts.append(f'<circle cx="{sx:.1f}" cy="{sy:.1f}" r="5.2" '
                         f'fill="#ffffff" stroke="#2e8b57" stroke-width="2"/>')
        elif st == 0:
            # 未见：红色实心方块
            h = 4.6
            parts.append(f'<rect x="{sx-h:.1f}" y="{sy-h:.1f}" '
                         f'width="{2*h:.1f}" height="{2*h:.1f}" '
                         f'fill="#c0392b"/>')
        else:
            parts.append(f'<circle cx="{sx:.1f}" cy="{sy:.1f}" r="2.4" '
                         f'fill="#cccccc"/>')
        # 特殊点高亮环
        if i == t_idx:
            parts.append(f'<circle cx="{sx:.1f}" cy="{sy:.1f}" r="8" '
                         f'fill="none" stroke="#1f6fb2" stroke-width="2.4"/>')
        elif i in n_idx:
            parts.append(f'<circle cx="{sx:.1f}" cy="{sy:.1f}" r="8" '
                         f'fill="none" stroke="#8e44ad" stroke-width="2.4"/>')

    parts.append('</svg>')
    return "\n".join(parts)


def build_a4_html(report, analysis_result, lang: str = "zh") -> str:
    """构建完整的 A4 报告 HTML 字符串（支持 zh / en）。"""
    T = REPORT_UI[lang]
    en = (lang == "en")
    eye_name = "Left eye (OS)" if analysis_result.eye == "OS" else "Right eye (OD)"
    overall_pass = analysis_result.overall_pass

    # 患者信息
    name = html.escape(report.patient_name or "—")
    raw_gender = report.gender or "—"
    if en:
        gender_map = {"男": "Male", "女": "Female", "M": "Male", "F": "Female",
                      "Male": "Male", "Female": "Female"}
        gender = html.escape(gender_map.get(raw_gender.strip(), raw_gender))
    else:
        gender = html.escape(raw_gender)
    dob = html.escape(report.birth_date or "—")
    pid = html.escape(report.patient_id or "—")
    exam_date = html.escape(report.exam_date or "—")

    # 可靠性指标
    def _rel(num, den):
        if den:
            return f"{num} ({num}/{den})" if en else f"{num} 次（{num}/{den}）"
        return f"{num}" if en else f"{num} 次"

    fl = _rel(report.fixation_loss, report.fl_total)
    fp = _rel(report.false_positive, report.fp_total)
    fn = _rel(report.false_negative, report.fn_total)

    # 视野图
    svg = render_grid_svg(analysis_result.eye, analysis_result.point_states)

    # 规则判定表
    rows = []
    for r in analysis_result.rules:
        icon = T["pass"] if r.passed else T["fail"]
        color = "#1e7d34" if r.passed else "#b3271f"
        plain = RULE_PLAIN[lang].get(r.rule_id, r.rule_name)
        rows.append(
            f'<tr>'
            f'<td style="width:46px;text-align:center;font-weight:bold;'
            f'color:{color}">{r.rule_id}</td>'
            f'<td>{html.escape(r.rule_name)}<br>'
            f'<span style="color:#666;font-size:12px">{html.escape(plain)}</span></td>'
            f'<td style="width:120px;color:{color};font-weight:bold">{icon}</td>'
            f'<td style="width:200px;color:#444;font-size:12px">{html.escape(r.detail)}</td>'
            f'</tr>'
        )
    rules_table = "\n".join(rows)

